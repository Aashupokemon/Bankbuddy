#!/usr/bin/env bash
#
# Creates the release signing key for BankBuddy, outside version control.
#
#   bash scripts/create-keystore.sh
#   source apps/mobile/keystore/keystore.env
#   npm run mobile:apk
#
# The key identifies the app to Android: keep it, back it up, and never commit it — losing it means
# installed builds can no longer be updated, only uninstalled and replaced.
#
# Options:
#   BANKBUDDY_KEYSTORE_PASSWORD   reuse a password instead of generating one
#   BANKBUDDY_DNAME              certificate subject (default: CN=BankBuddy Pilot, O=BankBuddy, C=IN)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KEYSTORE_DIR="$REPO_ROOT/apps/mobile/keystore"
KEYSTORE_FILE="$KEYSTORE_DIR/bankbuddy-release.jks"
ENV_FILE="$KEYSTORE_DIR/keystore.env"
ALIAS_NAME="bankbuddy"

die() {
  printf '\nerror: %s\n' "$*" >&2
  exit 1
}

[ -f "$KEYSTORE_FILE" ] && die "$KEYSTORE_FILE already exists. Refusing to overwrite the key that installed builds depend on."

keytool_bin="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$keytool_bin" >/dev/null 2>&1 || die "keytool not found. Set JAVA_HOME to a JDK 17 installation."

password="${BANKBUDDY_KEYSTORE_PASSWORD:-}"
if [ -z "$password" ]; then
  # 24 random bytes, printable, good enough for PKCS12 and not typed by hand.
  password="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 28)"
  [ "${#password}" -ge 20 ] || die "Could not generate a password; set BANKBUDDY_KEYSTORE_PASSWORD."
fi

mkdir -p "$KEYSTORE_DIR"

"$keytool_bin" -genkeypair \
  -keystore "$KEYSTORE_FILE" \
  -storetype PKCS12 \
  -alias "$ALIAS_NAME" \
  -keyalg RSA \
  -keysize 2048 \
  -validity 10000 \
  -storepass "$password" \
  -keypass "$password" \
  -dname "${BANKBUDDY_DNAME:-CN=BankBuddy Pilot, O=BankBuddy, C=IN}" \
  >/dev/null

cat >"$ENV_FILE" <<EOF
# Generated by scripts/create-keystore.sh. Keep this file out of version control.
# Load it with: source apps/mobile/keystore/keystore.env
export BANKBUDDY_KEYSTORE="$KEYSTORE_FILE"
export BANKBUDDY_KEYSTORE_PASSWORD="$password"
export BANKBUDDY_KEY_ALIAS="$ALIAS_NAME"
export BANKBUDDY_KEY_PASSWORD="$password"
EOF
chmod 600 "$ENV_FILE"

printf 'Created %s\n' "$KEYSTORE_FILE"
printf 'Credentials written to %s (chmod 600, gitignored).\n' "$ENV_FILE"
printf 'Next: source apps/mobile/keystore/keystore.env && npm run mobile:apk\n'
