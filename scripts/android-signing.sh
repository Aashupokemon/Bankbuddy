#!/usr/bin/env bash
#
# Points the generated Android project's release build at a real signing key.
#
# Without this the Expo template signs release APKs with the bundled debug keystore: the APK installs,
# but every rebuild clashes with the previous install ("signatures do not match" on update) and there
# is no key an owner can keep. The key material never lives in the repository.
#
# Usage:
#   scripts/create-keystore.sh                       # once, creates apps/mobile/keystore/
#   source apps/mobile/keystore/keystore.env         # exports the four variables below
#   npm run mobile:apk                               # build-apk.sh calls this script
#
# With none of the variables set the script is a no-op and the build keeps using the debug keystore,
# so a local demo build still works without secrets.
#
# Environment:
#   BANKBUDDY_KEYSTORE           path to the .jks / .keystore file
#   BANKBUDDY_KEYSTORE_PASSWORD  store password
#   BANKBUDDY_KEY_ALIAS          key alias (default: bankbuddy)
#   BANKBUDDY_KEY_PASSWORD       key password (defaults to the store password)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_DIR="${1:-$REPO_ROOT}"
ANDROID_APP_DIR="$PROJECT_DIR/apps/mobile/android/app"

log() { printf '\n== %s\n' "$*"; }
die() {
  printf '\nerror: %s\n' "$*" >&2
  exit 1
}

if [ -z "${BANKBUDDY_KEYSTORE:-}" ]; then
  log "No BANKBUDDY_KEYSTORE set — the release APK will be signed with the debug keystore."
  log "Generate one with scripts/create-keystore.sh when you need installs that update in place."
  exit 0
fi

[ -f "$BANKBUDDY_KEYSTORE" ] || die "BANKBUDDY_KEYSTORE points at $BANKBUDDY_KEYSTORE, which does not exist."
[ -n "${BANKBUDDY_KEYSTORE_PASSWORD:-}" ] || die "BANKBUDDY_KEYSTORE_PASSWORD is empty."
[ -f "$ANDROID_APP_DIR/build.gradle" ] || die "$ANDROID_APP_DIR/build.gradle is missing. Run expo prebuild first."

alias_name="${BANKBUDDY_KEY_ALIAS:-bankbuddy}"
key_password="${BANKBUDDY_KEY_PASSWORD:-$BANKBUDDY_KEYSTORE_PASSWORD}"

# A separate file applied at the end of app/build.gradle overrides the template's debug signing
# config without editing the generated file line by line.
cat >"$ANDROID_APP_DIR/release-signing.gradle" <<'GRADLE'
// Generated by scripts/android-signing.sh. android/ is not committed, and the values come from the
// environment so no password is ever written into the project.
android {
    signingConfigs {
        release {
            storeFile file(System.getenv("BANKBUDDY_KEYSTORE"))
            storePassword System.getenv("BANKBUDDY_KEYSTORE_PASSWORD")
            keyAlias System.getenv("BANKBUDDY_KEY_ALIAS")
            keyPassword System.getenv("BANKBUDDY_KEY_PASSWORD")
        }
    }
    buildTypes {
        release {
            signingConfig signingConfigs.release
        }
    }
}
GRADLE

if ! grep -q "release-signing.gradle" "$ANDROID_APP_DIR/build.gradle"; then
  {
    printf '\n// Release signing, from scripts/android-signing.sh.\n'
    printf 'apply from: "release-signing.gradle"\n'
  } >>"$ANDROID_APP_DIR/build.gradle"
fi

export BANKBUDDY_KEY_ALIAS="$alias_name"
export BANKBUDDY_KEY_PASSWORD="$key_password"

log "Release builds are signed with $BANKBUDDY_KEYSTORE (alias $alias_name)."
